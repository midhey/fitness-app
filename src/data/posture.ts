export const POSTURE_TOTAL_MIN = Math.round(POSTURE.reduce((s, p) => s + p.minutes, 0))

export interface ComplexInfo {
  id: ComplexId
  title: string
  subtitle: string
  items: PostureExercise[]
  minutes: number
}

export const COMPLEX_TITLES: Record<ComplexId, string> = {
  daily: 'Комплекс для осанки',
  back: 'Спина, таз и шея',
}

/** Комплекс на дату: ежедневный для осанки постоянный, «Спина и таз» меняется по дням */
export function complexFor(kind: ComplexId, date: string): ComplexInfo {
  const items = kind === 'daily' ? POSTURE : backComplexFor(date)
  return {
    id: kind,
    title: COMPLEX_TITLES[kind],
    subtitle: kind === 'daily' ? 'Ежедневно · голова, плечи, грудной отдел' : 'Вечером · свой набор на каждый день недели',
    items,
    minutes: Math.round(items.reduce((sum, e) => sum + e.minutes, 0)),
  }
}

